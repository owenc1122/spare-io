#!/usr/bin/env python3
"""Host-preview icon set for the app grid (Spare original; host only).

Our own four apps (nav / music / reader / pomodoro) come from the committed SVGs
via assets/icons/gen_icons.py (same rasterizer the firmware header uses), at the
grid box the page module asks for (FE_ICON_BOX). The stock apps' real icons are
supplied on the device by the port (stock launcher frame) and are NOT available
on the host, so the preview draws simple original placeholder glyphs for them.

Usage: gen_host_icons.py --box 44 --out build/frontend-preview/host_icons.h
"""
import argparse, math, os, sys
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.normpath(os.path.join(HERE, "..", "..", "assets", "icons"))
sys.path.insert(0, ICONS)
import gen_icons  # noqa: E402

SS = 8

def placeholder(name, box):
    n = box * SS
    im = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(im)
    k = n / 30.0                       # glyphs authored on a 30-unit grid, centre 15,15
    P = lambda x, y: (x * k, y * k)
    lw = max(1, int(2.6 * k))
    def line(pts, w=lw):
        q = [P(*p) for p in pts]
        d.line(q, fill=255, width=w, joint="curve")
        for x, y in (q[0], q[-1]):
            d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=255)
    def rr(x0, y0, x1, y1, r, fill=False):
        bb = [*P(x0, y0), *P(x1, y1)]
        if fill: d.rounded_rectangle(bb, radius=r * k, fill=255)
        else:    d.rounded_rectangle(bb, radius=r * k, outline=255, width=lw)
    def circ(cx, cy, r, fill=True, g=255):
        bb = [*P(cx - r, cy - r), *P(cx + r, cy + r)]
        if fill: d.ellipse(bb, fill=g)
        else:    d.ellipse(bb, outline=g, width=lw)
    if name == "prompt":        # teleprompter: framed text lines
        rr(1, 3, 29, 27, 5)
        for i, L in enumerate((14, 10, 14)): line([(8, 9 + i * 6), (8 + L, 9 + i * 6)])
    elif name == "gear":
        for i in range(8):
            a = i * math.pi / 4
            line([(15 + 9 * math.cos(a), 15 + 9 * math.sin(a)), (15 + 13.5 * math.cos(a), 15 + 13.5 * math.sin(a))], int(4.6 * k))
        circ(15, 15, 10.5); circ(15, 15, 4.5, g=0)
    elif name == "camera":
        rr(1, 8, 29, 27, 5, fill=True); rr(9, 4, 21, 10, 2, fill=True)
        circ(15, 17, 6.5, g=0); circ(15, 17, 3.5)
    elif name == "translate":
        line([(3, 6), (15, 6)]); line([(9, 3), (9, 6)]); line([(5, 6), (12, 16)]); line([(13, 6), (5, 17)])
        line([(15, 27), (21, 12), (27, 27)]); line([(17.5, 22), (24.5, 22)])
    elif name == "note":
        rr(4, 1, 26, 29, 5)
        for i in range(3): line([(10, 9 + i * 6), (20, 9 + i * 6)])
    elif name == "weather":
        circ(11, 11, 7.5); rr(5, 13, 28, 25, 6, fill=True)
    elif name == "calc":
        rr(4, 1, 26, 29, 5)
        for i in range(2):
            for j in range(2): circ(10 + 10 * i, 11 + 8 * j, 2.4)
    elif name == "info":
        circ(15, 15, 13.5, fill=False); circ(15, 8.5, 1.9); line([(15, 14), (15, 22)], int(2.9 * k))
    elif name == "mic":
        rr(10, 1, 20, 19, 5, fill=True)
        d.arc([*P(5, 6), *P(25, 24)], 0, 180, fill=255, width=lw)
        line([(15, 24), (15, 28)]); line([(10, 28.5), (20, 28.5)])
    elif name == "caption":
        rr(1, 5, 29, 25, 5)
        line([(7, 13), (13, 13)]); line([(16, 13), (23, 13)]); line([(7, 19), (18, 19)])
    elif name == "todo":
        for i in range(3):
            y = 7 + i * 8
            rr(2, y - 3, 8, y + 3, 1.5); line([(12, y), (27, y)])
        line([(3, 7), (5, 9), (9, 3)], int(2.0 * k))
    elif name == "bulb":
        circ(15, 12, 9.5, fill=False); line([(11, 24), (19, 24)]); line([(12, 28), (18, 28)])
        line([(15, 9), (15, 16)])
    return im.resize((box, box), Image.LANCZOS)

OURS = ["nav", "music", "reader", "pomodoro"]
STOCK = ["mic", "caption", "bulb", "todo", "prompt", "note", "gear", "camera", "translate", "weather", "calc", "info"]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--box", type=int, required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = ["/* GENERATED by backend-lvgl/host/gen_host_icons.py (host preview only). */",
           "#ifndef HOST_ICONS_H", "#define HOST_ICONS_H", "#include <stdint.h>",
           "#define HOST_ICON_BOX %d" % a.box, ""]
    for name in OURS + STOCK:
        if name in OURS:
            im = gen_icons.render(open(os.path.join(ICONS, name + ".svg")).read(), a.box)
        else:
            im = placeholder(name, a.box)
        data = list(im.getdata())
        out.append("static const uint8_t host_icon_%s[%d] = {" % (name, a.box * a.box))
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        out.append("};")
    out.append("#endif")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
